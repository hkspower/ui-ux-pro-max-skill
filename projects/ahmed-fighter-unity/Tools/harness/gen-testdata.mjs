/* Writes tests/TestData.cs from Assets/Resources/Data, so the harness runs
   against the tables the port actually ships rather than a copy typed by
   hand -- the old one still said SALMIYA GYM a rename ago. Run after every
   export:  node Tools/harness/gen-testdata.mjs  */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = dirname(fileURLToPath(import.meta.url));
const DATA = resolve(HERE, '../../Assets/Resources/Data');
const read = n => JSON.parse(readFileSync(join(DATA, n + '.json'), 'utf8')).items;
const q = s => '"' + String(s == null ? '' : s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const f = v => (+v).toFixed(6) + 'f';
const strs = a => 'new string[]{' + (a || []).map(q).join(',') + '}';
const link = l => `new WorldLink{to=${l.to},requiredAbility=${q(l.requiredAbility)},afterCleared=${l.afterCleared},distance=${f(l.distance)}}`;
const wave = w => `new WaveRow{triggerDistance=${f(w.triggerDistance)},tierOverride=${w.tierOverride},fighters=${strs(w.fighters)}}`;
const gate = g => `new GateRow{distance=${f(g.distance)},type=${q(g.type)},rewardAbility=${q(g.rewardAbility)},rewardExperience=${g.rewardExperience}}`;

const areas = read('world').map(a =>
  `        new WorldArea{index=${a.index},name=${q(a.name)},mapX=${a.mapX},mapY=${a.mapY},startArea=${a.startArea},west=${link(a.west)},east=${link(a.east)},door=${link(a.door)}},`);
const stages = read('stages').map(s =>
  `        new StageRow{name=${q(s.name)},index=${s.index},displayName=${q(s.displayName)},theme=${q(s.theme)},length=${f(s.length)},tier=${s.tier},bossStage=${s.bossStage},survival=${s.survival},waves=new WaveRow[]{${(s.waves||[]).map(wave).join(',')}},gates=new GateRow[]{${(s.gates||[]).map(gate).join(',')}}},`);
const strata = read('strata').map(r =>
  `        new StratumRow{area=${r.area},level=${q(r.level)},offset=${r.offset},height=${f(r.height)},shaftDistance=${f(r.shaftDistance)},shaftAbility=${q(r.shaftAbility)},waves=new WaveRow[]{${(r.waves||[]).map(wave).join(',')}},gates=new GateRow[]{${(r.gates||[]).map(gate).join(',')}}},`);
const fighters = read('fighters').map(r =>
  `        new FighterRow{name=${q(r.name)},displayName=${q(r.displayName)},maxHealth=${f(r.maxHealth)},boss=${r.boss},scale=${f(r.scale)},experienceValue=${r.experienceValue},moves=${strs(r.moves)}},`);

writeFileSync(join(HERE, 'tests/TestData.cs'), `// GENERATED by Tools/harness/gen-testdata.mjs from Assets/Resources/Data. Do not edit.
using Ahmed.Data;

public static class TestData
{
    public static WorldArea[] Areas = new WorldArea[] {
${areas.join('\n')}
    };

    public static StageRow[] Stages = new StageRow[] {
${stages.join('\n')}
    };

    public static StratumRow[] Strata = new StratumRow[] {
${strata.join('\n')}
    };

    public static FighterRow[] Fighters = new FighterRow[] {
${fighters.join('\n')}
    };

    /// <summary>The floors of one area, resolved, as GameData.Strata would hand them out.</summary>
    public static System.Collections.Generic.List<StratumRow> StrataOf(int area)
    {
        var found = new System.Collections.Generic.List<StratumRow>();
        foreach (StratumRow r in Strata) if (r.area == area) { r.Resolve(); found.Add(r); }
        return found;
    }
    public static FighterRow Fighter(string name)
    {
        foreach (FighterRow r in Fighters) if (r.name == name) return r;
        return null;
    }
}
`);
console.log(`TestData.cs: ${areas.length} areas, ${stages.length} stages, ${strata.length} strata rows, ${fighters.length} fighters`);
