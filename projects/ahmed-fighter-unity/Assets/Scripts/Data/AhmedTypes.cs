    [Serializable]
    public class GateRow
    {
        public float distance;
        public string type;
        public string rewardAbility;
        public int rewardExperience;

        [NonSerialized] public GateType Type;
        [NonSerialized] public Ability RewardAbility;

        public void Resolve()
        {
            Type = (GateType)Enum.Parse(typeof(GateType), type, true);
            RewardAbility = (Ability)Enum.Parse(typeof(Ability), rewardAbility, true);
        }
    }

    [Serializable]
    public class StageRow
    {
        public string name;
        public int index;
        public string displayName;
        public string displayNameArabic;
        public string theme;
        public string briefing;
        public string briefingArabic;
        public string hint;
        public float length;
        public int tier;
        public bool bossStage;
        public bool survival;
        public WaveRow[] waves;
        public GateRow[] gates;

        public void Resolve()
        {
            if (gates == null) { gates = new GateRow[0]; }
            if (waves == null) { waves = new WaveRow[0]; }
            for (int i = 0; i < gates.Length; i++) { gates[i].Resolve(); }
        }
    }

