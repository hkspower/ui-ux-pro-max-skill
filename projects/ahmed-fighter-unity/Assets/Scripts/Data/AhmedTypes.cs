    [Serializable]
    public class StyleStrike
    {
        public string attackRow;
        public string[] bands;
        public float weight;
        public float opensCombination;

        [NonSerialized] public RangeBand[] Bands;

        public void Resolve()
        {
            Bands = new RangeBand[bands == null ? 0 : bands.Length];
            for (int i = 0; i < Bands.Length; i++)
            {
                Bands[i] = (RangeBand)Enum.Parse(typeof(RangeBand), bands[i], true);
            }
        }

        public bool ThrownFrom(RangeBand band)
        {
            for (int i = 0; i < Bands.Length; i++)
            {
                if (Bands[i] == band) { return true; }
            }
            return false;
        }
    }

    /// <summary>
    /// A fighting style: where a fighter wants to stand, how it gets there,
    /// what it throws from where it is, and what it does after.
    ///
    /// Derived per archetype from the roster by the exporter rather than
    /// authored, so a style cannot drift away from the numbers it came from.
    /// </summary>
    [Serializable]
    public class StyleRow
    {
        public string name;
        public string displayName;

        public float preferredRange;
        public float rangeDiscipline;
        public float resetDistance;

        public float bounceRate;
        public float bounceAmplitude;
        public float circleTendency;
        public float circleSwitchTime;

        public StyleStrike[] strikes;
        public float attackInterval;
        public float rhythmJitter;
        public int maxComboLength;

        public float guardChance;
        public bool guardsWhileAdvancing;
        public float counterChance;

        public void Resolve()
        {
            if (strikes == null) { strikes = new StyleStrike[0]; }
            for (int i = 0; i < strikes.Length; i++) { strikes[i].Resolve(); }
        }

        /// <summary>
        /// Which band a distance falls in, given this style's own reach.
        /// Relative rather than absolute because "close" means something
        /// different to a lanky kickboxer than to a squat grappler, and a
        /// fixed threshold would leave the tall fighter with no mid range.
        /// </summary>
        public RangeBand BandFor(float distance)
        {
            float r = Mathf.Max(0.40f, preferredRange);
            if (distance <= r * 0.55f) { return RangeBand.Close; }
            if (distance <= r * 1.05f) { return RangeBand.Mid; }
            if (distance <= r * 1.85f) { return RangeBand.Long; }
            return RangeBand.Out;
        }

        /// <summary>
        /// Pick a strike legal at this band, weighted across this style plus
        /// anything the fighter has gained since (an enraged boss's finisher).
        ///
        /// Returns null when there is nothing to throw from here, which is a
        /// real answer and not a failure: it is what makes a boxer walk
        /// forward rather than swing at air.
        /// </summary>
        public StyleStrike ChooseStrike(RangeBand band, System.Collections.Generic.List<StyleStrike> extra)
        {
            // Weights are normalised across what is legal *now* rather than
            // authored to sum to one, so removing a strike from a style never
            // means re-tuning every other strike in it.
            float total = 0f;
            for (int i = 0; i < strikes.Length; i++)
            {
                if (Legal(strikes[i], band)) { total += strikes[i].weight; }
            }
            if (extra != null)
            {
                for (int i = 0; i < extra.Count; i++)
                {
                    if (Legal(extra[i], band)) { total += extra[i].weight; }
                }
            }
            if (total <= 0f) { return null; }

            float roll = UnityEngine.Random.Range(0f, total);
            for (int i = 0; i < strikes.Length; i++)
            {
                if (!Legal(strikes[i], band)) { continue; }
                roll -= strikes[i].weight;
                if (roll <= 0f) { return strikes[i]; }
            }
            if (extra != null)
            {
                for (int i = 0; i < extra.Count; i++)
                {
                    if (!Legal(extra[i], band)) { continue; }
                    roll -= extra[i].weight;
                    if (roll <= 0f) { return extra[i]; }
                }
            }
            return null;
        }

        private static bool Legal(StyleStrike s, RangeBand band)
        {
            return s != null && !string.IsNullOrEmpty(s.attackRow)
                && s.weight > 0f && s.ThrownFrom(band);
        }
    }

