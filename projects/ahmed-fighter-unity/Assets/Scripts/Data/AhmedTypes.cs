    /// <summary>
    /// How far away an opponent is, in the only terms that matter to choosing
    /// a strike. A kickboxer has an answer at Long; a boxer does not, and that
    /// absence is what makes him close the distance.
    /// </summary>
    public enum RangeBand { Out, Long, Mid, Close }

    /// <summary>
    /// The playfield is a strip: X runs along the stage, Z is depth, Y is up.
    ///
    /// Note the axes. The browser draws in canvas pixels with Y down, and the
    /// Unreal port runs X along with Y as depth and Z up. Unity is Y-up, so
    /// depth is Z here and nowhere else. Every one of these came across from
    /// AhmedGameplay in the Unreal build, converted from centimetres.
    /// </summary>
    public static class Playfield
    {
        public const float DepthMin = -4.20f;
        public const float DepthMax = 4.20f;

        /// <summary>Reserved width so fights never happen under the HUD.</summary>
        public const float ArenaWidth = 22.0f;

        public const float StaminaRegenPerSecond = 24f;
        public const float BlockDamageMultiplier = 0.20f;
        public const float ParryWindow = 0.20f;
        public const float ComboWindow = 0.95f;
        public const float ComboResetTime = 1.7f;
        public const float RageMax = 100f;

        /// <summary>At most this many enemies swing at once, so crowds stay fair.</summary>
        public const int MaxSimultaneousAttackers = 2;

        /// <summary>One canvas pixel in metres. See Tools/export/export.mjs.</summary>
        public const float PixelsToMetres = 0.024f;
    }

    /* ===================================================================
     * The tables.
     *
     * Every one of these is generated by Tools/export/export.mjs from the
     * browser project's assets/*.js, which is the source of truth for every
     * number in the game. Never edit the JSON: edit the assets (the control
     * panel next door is the comfortable way), re-export, press play.
     *
     * The field names have to match the JSON keys exactly, because that is
     * how JsonUtility binds -- and enums cross as strings rather than as the
     * integers JsonUtility would want, so that reordering an enum cannot
     * silently turn every jab into a kick. `Resolve` does the parsing.
     * =================================================================== */

    [Serializable]
    public class AttackRow
    {
        public string name;
        public string family;
        public float damage;
        public float startup;
        public float active;
        public float recovery;
        public float reach;
        public float depthTolerance;
        public float knockback;
        public float staminaCost;
        public bool heavy;
        public bool multiHit;

        [NonSerialized] public AttackFamily Family;

        public float TotalTime { get { return startup + active + recovery; } }

        public void Resolve()
        {
            Family = (AttackFamily)Enum.Parse(typeof(AttackFamily), family, true);
        }
    }

